function Ripple({ cx, cy, delay }: { cx: number; cy: number; delay: number }) {
  const origin = { transformOrigin: `${cx}px ${cy}px` };
  return (
    <>
      <motion.g
        style={origin}
        animate={{ scaleX: [1, 3.5], scaleY: [1, 2.5], opacity: [0.55, 0] }}
        transition={{ duration: 2.5, delay, repeat: Infinity, repeatDelay: 2, ease: "easeOut" }}
      >
        <ellipse cx={cx} cy={cy} rx={13} ry={4} stroke={C} strokeWidth="1.5" fill="none" />
      </motion.g>
      <motion.g
        style={origin}
        animate={{ scaleX: [1, 2.5], scaleY: [1, 2], opacity: [0.35, 0] }}
        transition={{ duration: 2.5, delay: delay + 0.55, repeat: Infinity, repeatDelay: 2, ease: "easeOut" }}
      >
        <ellipse cx={cx} cy={cy} rx={8} ry={3} stroke={C} strokeWidth="1" fill="none" />
      </motion.g>
    </>
  );
}

function Splash({ cx, cy, delay }: { cx: number; cy: number; delay: number }) {
  const drops: [number, number][] = [
    [0, -24], [8, -28], [-8, -28],
    [14, -18], [-14, -18],
    [4, -32], [-4, -32],
  ];
  return (
    <motion.g
      style={{ transformOrigin: `${cx}px ${cy}px` }}
      animate={{
        opacity: [0, 0, 1, 1, 0],
        scale:   [0.6, 0.6, 1, 1.1, 0.3],
      }}
      transition={{ duration: 0.9, delay, repeat: Infinity, repeatDelay: 7, ease: "easeOut" }}
    >
      {drops.map(([dx, dy], i) => (
        <line
          key={i}
          x1={cx + dx * 0.35} y1={cy + dy * 0.35}
          x2={cx + dx}        y2={cy + dy}
          stroke={C} strokeWidth="2" strokeLinecap="round"
        />
      ))}
      <ellipse cx={cx} cy={cy - 1} rx={5} ry={2.5} stroke={C} strokeWidth="1.5" fill="none" />
    </motion.g>
  );
}

